-- Safe to re-run. Existing fan_comments rows and policies are preserved.
-- Public comments remain readable by everyone; authenticated users can insert only their own comments.

create table if not exists public.fan_comments (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    content text not null check (char_length(trim(content)) between 1 and 1000),
    created_at timestamptz not null default now()
);
alter table public.fan_comments enable row level security;
grant select on table public.fan_comments to anon, authenticated;
grant insert on table public.fan_comments to authenticated;

drop policy if exists "Public can read fan comments" on public.fan_comments;
create policy "Public can read fan comments" on public.fan_comments for select to anon, authenticated using (true);
drop policy if exists "Authenticated users can insert their own comments" on public.fan_comments;
create policy "Authenticated users can insert their own comments" on public.fan_comments for insert to authenticated
with check ((select auth.uid()) = user_id and char_length(trim(content)) between 1 and 1000);

-- Public profile fields only: never store email addresses or passwords in this table.
create table if not exists public.profiles (
    user_id uuid primary key references auth.users (id) on delete cascade,
    display_name text not null default '粉丝' check (char_length(trim(display_name)) between 1 and 40),
    avatar_url text,
    updated_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
grant select on table public.profiles to anon, authenticated;
grant insert, update on table public.profiles to authenticated;

drop policy if exists "Public can read profile display data" on public.profiles;
create policy "Public can read profile display data" on public.profiles for select to anon, authenticated using (true);
drop policy if exists "Users can insert their own profile" on public.profiles;
create policy "Users can insert their own profile" on public.profiles for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile" on public.profiles for update to authenticated
using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (user_id, display_name)
  values (new.id, coalesce(nullif(trim(new.raw_user_meta_data ->> 'display_name'), ''), '粉丝'))
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
after insert on auth.users
for each row execute procedure public.handle_new_auth_user();

-- Backfill existing accounts without changing any existing comments.
insert into public.profiles (user_id, display_name)
select id, coalesce(nullif(trim(raw_user_meta_data ->> 'display_name'), ''), '粉丝')
from auth.users
on conflict (user_id) do nothing;

-- Public avatars are readable; uploads are confined to a folder named with the caller's auth UID.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('avatars', 'avatars', true, 2097152, array['image/png','image/jpeg','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 2097152, allowed_mime_types = array['image/png','image/jpeg','image/webp'];

drop policy if exists "Avatar images are publicly readable" on storage.objects;
create policy "Avatar images are publicly readable" on storage.objects for select using (bucket_id = 'avatars');
drop policy if exists "Users can upload their own avatar files" on storage.objects;
create policy "Users can upload their own avatar files" on storage.objects for insert to authenticated
with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = (select auth.uid())::text);
drop policy if exists "Users can update their own avatar files" on storage.objects;
create policy "Users can update their own avatar files" on storage.objects for update to authenticated
using (bucket_id = 'avatars' and (storage.foldername(name))[1] = (select auth.uid())::text)
with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = (select auth.uid())::text);
drop policy if exists "Users can delete their own avatar files" on storage.objects;
create policy "Users can delete their own avatar files" on storage.objects for delete to authenticated
using (bucket_id = 'avatars' and (storage.foldername(name))[1] = (select auth.uid())::text);
