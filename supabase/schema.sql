-- Run this script in Supabase Dashboard -> SQL Editor.
-- Public visitors can read comments. Only authenticated users can insert their own comments.
-- No UPDATE or DELETE policies are intentionally provided for this first version.

create table if not exists public.fan_comments (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    content text not null check (char_length(trim(content)) between 1 and 1000),
    created_at timestamptz not null default now()
);

alter table public.fan_comments enable row level security;

grant select on table public.fan_comments to anon, authenticated;
grant insert on table public.fan_comments to authenticated;

drop policy if exists "Public can read fan comments" on public.fan_comments;
create policy "Public can read fan comments"
    on public.fan_comments
    for select
    to anon, authenticated
    using (true);

drop policy if exists "Authenticated users can insert their own comments" on public.fan_comments;
create policy "Authenticated users can insert their own comments"
    on public.fan_comments
    for insert
    to authenticated
    with check (
        (select auth.uid()) = user_id
        and char_length(trim(content)) between 1 and 1000
    );
